#!/usr/bin/env python3
"""Make the built-in test samples of version 0.1: synthetic, so they belong to nobody.

    0  pluck  plucked string at C4 (261.63 Hz), additive, 0.75 s: pitch and harmonics
    1  hat    noise burst, highpassed, 40 ms decay, 0.25 s: high frequencies (aliasing when pitched down)
    2  chord  C major triad of band-limited saws, 0.6 s: a tonal mixture

All 48 kHz, 16 bit, peaks at -1 dBFS. Writes a C file (default build/test_samples.c) and, with
--wav DIR, a WAV of each to listen to.

    python3 machine/test_samples.py [--out build/test_samples.c] [--wav build/test-samples]
"""
import argparse
import math
import struct
import wave
from pathlib import Path

RATE = 48000
HERE = Path(__file__).resolve().parent.parent


class Lcg:
    """Fixed pseudo-random numbers, so every build makes the same samples."""

    def __init__(self, seed):
        self.x = seed

    def __call__(self):
        self.x = (self.x * 1664525 + 1013904223) & 0xFFFFFFFF
        return self.x / 2147483648.0 - 1.0


def partials(out, f, amps, tau):
    """Adds band-limited harmonics of f (none above 20 kHz): amps(h) and decay times tau(h) in seconds."""
    for h in range(1, int(20000 // f) + 1):
        a, t = amps(h), tau(h)
        if a == 0:
            continue
        w = 2 * math.pi * f * h / RATE
        z, s = complex(math.cos(w), math.sin(w)), complex(1.0, 0.0)   # s turns by w each frame
        d, g = math.exp(-1.0 / (t * RATE)), a
        for i in range(len(out)):
            out[i] += g * s.imag
            s *= z
            g *= d


def pluck():
    """A plucked string at C4: harmonics 1/h, shaped by plucking at 30 % of the length, the higher
    ones dying away faster."""
    out = [0.0] * int(0.75 * RATE)
    partials(out, 261.63, lambda h: math.sin(math.pi * h * 0.3) / h, lambda h: 0.6 / (1 + 0.15 * h))
    return out


def hat():
    n = int(0.25 * RATE)
    rnd = Lcg(2)
    out, last = [], 0.0
    for i in range(n):
        x = rnd()
        hp, last = x - last, x                  # first difference: a gentle highpass
        out.append(hp * math.exp(-i / (0.040 * RATE)))
    return out


def chord():
    """C major triad of band-limited saws, 5 ms attack, 0.35 s decay."""
    n = int(0.6 * RATE)
    out = [0.0] * n
    for f in (261.63, 329.63, 392.00):
        partials(out, f, lambda h: 1.0 / h, lambda h: 0.35)
    for i in range(min(n, int(0.005 * RATE))):
        out[i] *= i / (0.005 * RATE)
    return out


def to_int16(x):
    peak = max(abs(v) for v in x) or 1.0
    scale = 32767 * 10 ** (-1 / 20) / peak
    return [int(round(v * scale)) for v in x]


SAMPLES = (("pluck", pluck), ("hat", hat), ("chord", chord))


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out", type=Path, default=HERE / "build" / "test_samples.c")
    ap.add_argument("--wav", type=Path, help="also write each sample as a WAV into this folder")
    args = ap.parse_args()

    made = [(name, to_int16(fn())) for name, fn in SAMPLES]
    lines = ["/* Generated by machine/test_samples.py - do not edit. */",
             '#include "test_samples.h"', ""]
    for name, pcm in made:
        lines.append("static const int16_t %s[%d] = {" % (name, len(pcm)))
        for i in range(0, len(pcm), 16):
            lines.append("    " + ", ".join(str(v) for v in pcm[i:i + 16]) + ",")
        lines.append("};")
        lines.append("")
    lines.append("const struct smp_test_sample smp_test[SMP_TEST_COUNT] = {")
    for name, pcm in made:
        lines.append("    { %s, %d }," % (name, len(pcm)))
    lines.append("};")
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n")
    print("%s: %s" % (args.out, ", ".join("%s %d frames" % (n, len(p)) for n, p in made)))

    if args.wav:
        args.wav.mkdir(parents=True, exist_ok=True)
        for i, (name, pcm) in enumerate(made):
            w = wave.open(str(args.wav / ("%d-%s.wav" % (i, name))), "wb")
            w.setnchannels(1)
            w.setsampwidth(2)
            w.setframerate(RATE)
            w.writeframes(b"".join(struct.pack("<h", v) for v in pcm))
            w.close()


if __name__ == "__main__":
    main()
