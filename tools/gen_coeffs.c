/* gen_coeffs: writes src/smp_coeffs.c, the table the core plays with.

       gen_coeffs proto FP FS WS LIFT_DB > src/smp_coeffs.c
       gen_coeffs kaiser FC BETA > src/smp_coeffs.c

   The parameters are those of design_proto and design_kaiser (design.h); the Makefile holds
   the ones in use. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "design.h"

int main(int argc, char **argv)
{
    static int16_t table[SMP_PHASES][SMP_TAPS];
    int32_t worst;
    int p, k;

    if (argc == 6 && !strcmp(argv[1], "proto"))
        worst = design_proto(atof(argv[2]), atof(argv[3]), atof(argv[4]), atof(argv[5]), table);
    else if (argc == 4 && !strcmp(argv[1], "kaiser"))
        worst = design_kaiser(atof(argv[2]), atof(argv[3]), table);
    else {
        fprintf(stderr, "usage: gen_coeffs proto FP FS WS LIFT_DB | gen_coeffs kaiser FC BETA\n");
        return 2;
    }
    if (worst < 0 || worst >= 65536) {
        fprintf(stderr, "gen_coeffs: these parameters give taps the core cannot use\n");
        return 1;
    }
    printf("/* Generated by tools/gen_coeffs");
    for (k = 1; k < argc; k++)
        printf(" %s", argv[k]);
    printf(" - do not edit.\n");
    if (!strcmp(argv[1], "proto"))
        printf("   One least-squares prototype of %d taps, cut into rows and centred: passband to %s\n"
               "   cycles per frame (bump %s dB at 10 kHz), stopband from %s, weight %s.\n",
               SMP_TAPS * SMP_PHASES, argv[2], argv[5], argv[3], argv[4]);
    else
        printf("   Kaiser-windowed sinc, cutoff %s cycles per frame, beta %s.\n", argv[2], argv[3]);
    printf("   %d phases of %d taps; rows sum to 32768, the largest sum of absolute taps is %ld. */\n",
           SMP_PHASES, SMP_TAPS, (long)worst);
    printf("#include \"smp_core.h\"\n\n");
    printf("const int16_t smp_coeffs[SMP_PHASES][SMP_TAPS] = {\n");
    for (p = 0; p < SMP_PHASES; p++) {
        printf("    {");
        for (k = 0; k < SMP_TAPS; k++)
            printf("%6d%s", table[p][k], k + 1 < SMP_TAPS ? "," : "");
        printf(" },\n");
    }
    printf("};\n");
    return 0;
}
