#!/usr/bin/env python3
"""Writes src/smp_filter_tab.c: the coefficient table of SAMPLE's filter (src/smp_filter.h).

The filter follows the Model:Samples' laws, measured on its OS (TECHNICAL.md, section 16), with
its own formulas and this table; nothing of Elektron's is in here. For a cutoff index i (0..16384,
the knob's 8.8 word, or its distance from the centre on the highpass side) and a resonance word R
(0..32768, 8.8), the two poles sit at radius r and angle theta:

    fc    = 4.918 Hz * 4400^(i / 16384)             (5 Hz .. 21.6 kHz, 2 semitones per knob step)
    w0    = 2 pi fc / 48000
    red   = 1 - (fc / 24000)^2.5                     (less resonance towards the top)
    Q     = 0.4918 * 43.8^(R red / 32512)            (0.49 .. 21.5)
    r     = exp(-w0 / (2 Q))
    theta = w0 * (1 - 0.70 exp(-R / 3300) - 0.233 exp(-R / 381))   (nearly real poles at R = 0)

The filter realises them as the Chamberlin state-variable form with f = |1 - r e^(j theta)| and
q = (1 - r^2) / f, which places any such pair exactly. The table holds f/2 and q/2 in Q31 on a
grid of 129 cutoff points (every 128) by 17 resonance points (every 2048); the filter interpolates
bilinearly. Usage: tools/gen_filter_table.py > src/smp_filter_tab.c"""
import math

NI, NR = 129, 17
STEP_I, STEP_R = 128, 2048
FS = 48000.0
F0, FRATIO = 4.918, 4400.0
Q0, QRATIO = 0.4918, 43.8
S_DEPTH, S_TAU = 0.70, 3300.0
S_DEPTH2, S_TAU2 = 0.233, 381.0
RED_F, RED_P = 24000.0, 2.5


def poles(i, R):
    fc = F0 * FRATIO ** (i / 16384.0)
    w0 = 2 * math.pi * fc / FS
    red = 1 - (fc / RED_F) ** RED_P
    Q = Q0 * QRATIO ** (R * red / 32512.0)
    r = math.exp(-w0 / (2 * Q))
    theta = w0 * (1 - S_DEPTH * math.exp(-R / S_TAU) - S_DEPTH2 * math.exp(-R / S_TAU2))
    return r, theta


def coefs(i, R):
    r, theta = poles(i, R)
    f = math.sqrt(1 - 2 * r * math.cos(theta) + r * r)
    q = (1 - r * r) / f
    return f / 2, q / 2


def q31(x):
    v = int(round(x * (1 << 31)))
    return max(-(1 << 31), min((1 << 31) - 1, v))


def main():
    print("/* Generated by tools/gen_filter_table.py; see there and src/smp_filter.h. */")
    print("#include \"smp_filter.h\"\n")
    print("const int32_t smp_filter_tab[SMP_FILTER_NR][SMP_FILTER_NI][2] = {")
    for ri in range(NR):
        R = ri * STEP_R
        print("    {   /* R = %d */" % R)
        row = []
        for ii in range(NI):
            f2, q2 = coefs(ii * STEP_I, R)
            row.append("{%d, %d}" % (q31(f2), q31(q2)))
        for k in range(0, NI, 3):
            print("        " + ", ".join(row[k:k + 3]) + ",")
        print("    },")
    print("};")


if __name__ == "__main__":
    main()
